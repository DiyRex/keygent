#!/usr/bin/env sh
# Render the Homebrew formula for one release from its signed SHA256SUMS.
# Usage: scripts/brew-formula.sh <tag> <SHA256SUMS> [base_url] > Formula/keygent.rb
set -eu
TAG="$1"; SUMS="$2"
BASE="${3:-https://github.com/DiyRex/keygent/releases/download/$TAG}"
printf '%s' "$TAG" | grep -Eq '^v[0-9]+\.[0-9]+\.[0-9]+' || { echo "brew-formula: bad tag '$TAG'" >&2; exit 2; }

sum() {
  s=$(awk -v f="keygent-$TAG-$1.tar.gz" '$2 == f { print $1 }' "$SUMS")
  printf '%s' "$s" | grep -Eq '^[0-9a-f]{64}$' || { echo "brew-formula: no checksum for $1" >&2; exit 1; }
  printf '%s' "$s"
}
# Resolve every checksum first: an exit inside $(...) below would only leave the subshell.
MA=$(sum aarch64-apple-darwin); MI=$(sum x86_64-apple-darwin)
LA=$(sum aarch64-unknown-linux-musl); LI=$(sum x86_64-unknown-linux-musl)
block() {
  printf '    %s do\n      url "%s/keygent-%s-%s.tar.gz"\n      sha256 "%s"\n    end\n' "$1" "$BASE" "$TAG" "$2" "$3"
}

cat <<RUBY
# typed: strict
# frozen_string_literal: true

# Generated by scripts/brew-formula.sh in DiyRex/keygent for $TAG. Do not edit by hand.
class Keygent < Formula
  desc "Let AI coding agents use secrets without seeing them"
  homepage "https://github.com/DiyRex/keygent"
  version "${TAG#v}"
  license "Apache-2.0"

  on_macos do
$(block on_arm aarch64-apple-darwin "$MA")
$(block on_intel x86_64-apple-darwin "$MI")
  end

  on_linux do
$(block on_arm aarch64-unknown-linux-musl "$LA")
$(block on_intel x86_64-unknown-linux-musl "$LI")
  end

  def install
    bin.install "keygent"
  end

  def caveats
    <<~EOS
      After an upgrade, restart the broker so the new binary holds your vault:
        keygent seal && keygent unseal
      Hooks call #{HOMEBREW_PREFIX}/bin/keygent, which stays valid across upgrades.
    EOS
  end

  test do
    assert_match "keygent", shell_output("#{bin}/keygent help")
  end
end
RUBY
